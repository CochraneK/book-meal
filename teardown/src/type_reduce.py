def event_base_of(name, raw_type=""):
    """
    事件 → 叙事功能基类。返回 (基类, 依据)。

    依据字段用于报告里「为什么归到这一类」的可追溯性：
      类型命中时返回原始类型（如 "日常/医疗"），关键词命中时返回具体词，
      否则返回空串。
    """
    # ---- 第一级：原始类型 ----
    t = (raw_type or "").strip()
    if t:
        # 去掉括号补充（「日常（回忆）」）后按斜杠拆分，取首个可识别 token
        head = re.sub(r"[（(].*?[)）]", "", t)
        for token in re.split(r"[/、,，]", head):
            token = token.strip()
            if not token:
                continue
            if token in EVENT_TYPE_ALIAS:
                return EVENT_TYPE_ALIAS[token], t
        # 类型本身已是基类名
        if head in EVENT_BASES:
            return head, t

    # ---- 第二级：事件名关键词 ----
    text = (name or "").strip()
    if text:
        for base, kws in EVENT_KEYWORDS:
            for kw in kws:
                if kw in text:
                    return base, kw
    return EVENT_FALLBACK, ""


