def place_base_of(name, raw_type=""):
    """地点 → 功能基类。返回 (基类, 依据)。

    与事件相反，这里**名称优先**：原始类型在「室内/设施/建筑」之间摇摆，
    同一个清洁中心会被不同 agent 标成不同类；而地名本身稳定。
    """
    text = (name or "").strip()
    if text:
        for base, kws in PLACE_KEYWORDS:
            for kw in kws:
                if kw in text:
                    return base, kw
    t = (raw_type or "").strip()
    if t:
        head = re.sub(r"[（(].*?[)）]", "", t)
        for token in re.split(r"[/、,，]", head):
            token = token.strip()
            if token in PLACE_TYPE_ALIAS and PLACE_TYPE_ALIAS[token]:
                return PLACE_TYPE_ALIAS[token], t
    return PLACE_FALLBACK, ""


